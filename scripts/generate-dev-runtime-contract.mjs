import { readFile, writeFile } from 'node:fs/promises'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const inputPath = path.join(root, 'docs/specs/dev-runtime-operations.json')
const outputPath = path.join(root, 'packages/types/src/dev-runtime-registry.ts')
const metadataOutputPath = path.join(root, 'packages/types/src/dev-runtime-metadata.ts')
const registry = JSON.parse(await readFile(inputPath, 'utf8'))
const operationEntries = Object.entries(registry.operations)

function operationMetadataExportName(operation) {
  return `devOperationMetadataFor_${operation.replace(/[^A-Za-z0-9_$]/g, '_')}`
}

const operationMetadataExportNames = new Map()
for (const [operation] of operationEntries) {
  const exportName = operationMetadataExportName(operation)
  const previousOperation = operationMetadataExportNames.get(exportName)
  if (previousOperation)
    throw new Error(
      `${previousOperation} and ${operation} collide as generated metadata export ${exportName}`
    )
  operationMetadataExportNames.set(exportName, operation)
}

const operationCapabilities = [
  ...new Set(operationEntries.flatMap(([, definition]) => definition.capabilities)),
].toSorted((left, right) => (left < right ? -1 : left > right ? 1 : 0))

const targetIdFields = {
  acp_connection: 'acpConnectionId',
  browser_lane: 'browserLaneId',
  cleanup_policy: 'cleanupPolicyId',
  computeruse_lane: 'computerUseLaneId',
  device_inventory: 'inventoryId',
  device_session: 'deviceSessionId',
  group: 'groupId',
  process: 'processRecordId',
  project: 'projectId',
  pull_request: 'pullRequestId',
  repository: 'repoId',
  runtime_session: 'runtimeSessionId',
  terminal: 'terminalId',
  workspace_root: 'worktreeId',
  worktree: 'worktreeId',
  workspace_path: 'worktreeId',
}

function operationDefinition([operation, definition]) {
  const resourceKind = definition.resource?.split(':')[0]
  if (resourceKind && !targetIdFields[resourceKind])
    throw new Error(`${operation} has unmapped resource kind ${resourceKind}`)
  if (
    definition.capabilities.some(
      (capability, index) =>
        index > 0 && capability.localeCompare(definition.capabilities[index - 1]) <= 0
    )
  )
    throw new Error(`${operation} capabilities must be sorted and unique`)
  const resource = resourceKind
    ? `{ kind: ${JSON.stringify(resourceKind)}, idField: ${JSON.stringify(targetIdFields[resourceKind])} }`
    : 'null'
  const stream = definition.stream ? JSON.stringify(definition.stream) : 'null'
  return `  ${JSON.stringify(operation)}: {\n    body: ${JSON.stringify(definition.body)},\n    capabilities: ${JSON.stringify(definition.capabilities)},\n    reply: ${JSON.stringify(definition.reply)},\n    resource: ${resource},\n    stream: ${stream},\n  }`
}

const unformattedSource = `// Generated by scripts/generate-dev-runtime-contract.mjs from\n// docs/specs/dev-runtime-operations.json. Do not edit by hand.\n\nexport const devRuntimeTransportMethods = ${JSON.stringify(registry.transportMethods, null, 2)} as const\n\nexport const devStreamProtocolDefinitions = ${JSON.stringify(registry.streamProtocols, null, 2)} as const\n\nexport const devOperationDefinitions = {\n${Object.entries(registry.operations).map(operationDefinition).join(',\n')}\n} as const\n\nexport const devOperations = Object.freeze(Object.keys(devOperationDefinitions)) as readonly (keyof typeof devOperationDefinitions)[]\n`

function operationMetadataResource(operation, definition) {
  const resourceKind = definition.resource?.split(':')[0]
  if (resourceKind && !targetIdFields[resourceKind])
    throw new Error(`${operation} has unmapped resource kind ${resourceKind}`)
  return resourceKind
    ? `{ kind: ${JSON.stringify(resourceKind)}, idField: ${JSON.stringify(targetIdFields[resourceKind])} }`
    : 'null'
}

const operationMetadataExports = operationEntries
  .map(([operation, definition]) => {
    const exportName = operationMetadataExportName(operation)
    const resource = operationMetadataResource(operation, definition)
    return `export const ${exportName} = { operation: ${JSON.stringify(operation)}, capabilities: ${JSON.stringify(definition.capabilities)}, resource: ${resource} } as const`
  })
  .join('\n\n')
const operationMetadataAggregate = operationEntries
  .map(([operation]) => {
    const exportName = operationMetadataExportName(operation)
    return `  ${JSON.stringify(operation)}: { capabilities: ${exportName}.capabilities, resource: ${exportName}.resource }`
  })
  .join(',\n')
const unformattedMetadataSource = `// Generated by scripts/generate-dev-runtime-contract.mjs from\n// docs/specs/dev-runtime-operations.json. Do not edit by hand.\n// Browser-safe operation metadata; request DSL and reply schema names stay in the server registry.\n\n${operationMetadataExports}\n\nexport const devOperationMetadata = {\n${operationMetadataAggregate}\n} as const\n\n// Unique capabilities required by operations. Client-preference-only capabilities\n// remain part of the capability-snapshot decoder universe, not this provider list.\nexport const devOperationCapabilities = Object.freeze(${JSON.stringify(operationCapabilities)} as const)\n`

const formatted = spawnSync('bunx', ['oxfmt', '--stdin-filepath', outputPath], {
  cwd: root,
  encoding: 'utf8',
  input: unformattedSource,
})
if (formatted.status !== 0) {
  process.stderr.write(formatted.stderr)
  process.exit(formatted.status ?? 1)
}
const source = formatted.stdout

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '')
  if (current !== source) {
    console.error('packages/types/src/dev-runtime-registry.ts is out of date')
    process.exit(1)
  }
  const currentMetadata = await readFile(metadataOutputPath, 'utf8').catch(() => '')
  const formattedMetadata = spawnSync('bunx', ['oxfmt', '--stdin-filepath', metadataOutputPath], {
    cwd: root,
    encoding: 'utf8',
    input: unformattedMetadataSource,
  })
  if (formattedMetadata.status !== 0) {
    process.stderr.write(formattedMetadata.stderr)
    process.exit(formattedMetadata.status ?? 1)
  }
  if (currentMetadata !== formattedMetadata.stdout) {
    console.error('packages/types/src/dev-runtime-metadata.ts is out of date')
    process.exit(1)
  }
} else {
  await writeFile(outputPath, source)
  const formattedMetadata = spawnSync('bunx', ['oxfmt', '--stdin-filepath', metadataOutputPath], {
    cwd: root,
    encoding: 'utf8',
    input: unformattedMetadataSource,
  })
  if (formattedMetadata.status !== 0) {
    process.stderr.write(formattedMetadata.stderr)
    process.exit(formattedMetadata.status ?? 1)
  }
  await writeFile(metadataOutputPath, formattedMetadata.stdout)
}
