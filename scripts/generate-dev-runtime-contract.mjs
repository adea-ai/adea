import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const inputPath = path.join(root, 'docs/specs/dev-runtime-operations.json')
const outputPath = path.join(root, 'packages/types/src/dev-runtime-registry.ts')
const metadataOutputPath = path.join(root, 'packages/types/src/dev-runtime-metadata.ts')
const operationMetadataDirectory = path.join(
  root,
  'packages/types/src/dev-runtime-operation-metadata'
)
const registry = JSON.parse(await readFile(inputPath, 'utf8'))
const operationEntries = Object.entries(registry.operations)

function operationMetadataExportName(operation) {
  return `devOperationMetadataFor_${operation.replace(/[^A-Za-z0-9_$]/g, '_')}`
}

const operationMetadataExportNames = new Map()
const operationMetadataFileNames = new Map()
for (const [operation] of operationEntries) {
  const exportName = operationMetadataExportName(operation)
  const previousOperation = operationMetadataExportNames.get(exportName)
  if (previousOperation)
    throw new Error(
      `${previousOperation} and ${operation} collide as generated metadata export ${exportName}`
    )
  operationMetadataExportNames.set(exportName, operation)

  const fileName = `${operation.replace(/[^A-Za-z0-9_$]/g, '_')}.ts`
  const previousFileOperation = operationMetadataFileNames.get(fileName)
  if (previousFileOperation)
    throw new Error(
      `${previousFileOperation} and ${operation} collide as generated metadata file ${fileName}`
    )
  if (fileName === 'index.ts' || fileName === 'capabilities.ts')
    throw new Error(`${operation} collides with a reserved generated metadata file`)
  operationMetadataFileNames.set(fileName, operation)
}

const operationCapabilities = [
  ...new Set(operationEntries.flatMap(([, definition]) => definition.capabilities)),
].toSorted((left, right) => (left < right ? -1 : left > right ? 1 : 0))

const targetIdFields = {
  acp_connection: 'acpConnectionId',
  browser_lane: 'browserLaneId',
  cleanup_policy: 'cleanupPolicyId',
  computeruse_lane: 'computerUseLaneId',
  device_inventory: 'inventoryId',
  device_session: 'deviceSessionId',
  group: 'groupId',
  process: 'processRecordId',
  project: 'projectId',
  pull_request: 'pullRequestId',
  repository: 'repoId',
  runtime_session: 'runtimeSessionId',
  terminal: 'terminalId',
  workspace_root: 'worktreeId',
  worktree: 'worktreeId',
  workspace_path: 'worktreeId',
}

function operationDefinition([operation, definition]) {
  const resourceKind = definition.resource?.split(':')[0]
  if (resourceKind && !targetIdFields[resourceKind])
    throw new Error(`${operation} has unmapped resource kind ${resourceKind}`)
  if (
    definition.capabilities.some(
      (capability, index) =>
        index > 0 && capability.localeCompare(definition.capabilities[index - 1]) <= 0
    )
  )
    throw new Error(`${operation} capabilities must be sorted and unique`)
  const resource = resourceKind
    ? `{ kind: ${JSON.stringify(resourceKind)}, idField: ${JSON.stringify(targetIdFields[resourceKind])} }`
    : 'null'
  const stream = definition.stream ? JSON.stringify(definition.stream) : 'null'
  return `  ${JSON.stringify(operation)}: {\n    body: ${JSON.stringify(definition.body)},\n    capabilities: ${JSON.stringify(definition.capabilities)},\n    reply: ${JSON.stringify(definition.reply)},\n    resource: ${resource},\n    stream: ${stream},\n  }`
}

const unformattedSource = `// Generated by scripts/generate-dev-runtime-contract.mjs from\n// docs/specs/dev-runtime-operations.json. Do not edit by hand.\n\nexport const devRuntimeTransportMethods = ${JSON.stringify(registry.transportMethods, null, 2)} as const\n\nexport const devStreamProtocolDefinitions = ${JSON.stringify(registry.streamProtocols, null, 2)} as const\n\nexport const devOperationDefinitions = {\n${Object.entries(registry.operations).map(operationDefinition).join(',\n')}\n} as const\n\nexport const devOperations = Object.freeze(Object.keys(devOperationDefinitions)) as readonly (keyof typeof devOperationDefinitions)[]\n`

function operationMetadataResource(operation, definition) {
  const resourceKind = definition.resource?.split(':')[0]
  if (resourceKind && !targetIdFields[resourceKind])
    throw new Error(`${operation} has unmapped resource kind ${resourceKind}`)
  return resourceKind
    ? `{ kind: ${singleQuoted(resourceKind)}, idField: ${singleQuoted(targetIdFields[resourceKind])} }`
    : 'null'
}

function singleQuoted(value) {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
}

const operationMetadataFiles = new Map(
  operationEntries.map(([operation, definition]) => {
    const exportName = operationMetadataExportName(operation)
    const fileName = `${operation.replace(/[^A-Za-z0-9_$]/g, '_')}.ts`
    const capabilities = definition.capabilities.map(singleQuoted).join(', ')
    const source = `// Generated by scripts/generate-dev-runtime-contract.mjs from\n// docs/specs/dev-runtime-operations.json. Do not edit by hand.\n\nexport const ${exportName} = {\n  operation: ${singleQuoted(operation)},\n  capabilities: [${capabilities}],\n  resource: ${operationMetadataResource(operation, definition)},\n} as const\n`
    return [fileName, source]
  })
)

const operationMetadataCapabilitiesSource = `// Generated by scripts/generate-dev-runtime-contract.mjs from\n// docs/specs/dev-runtime-operations.json. Do not edit by hand.\n// Client-preference-only capabilities remain in the decoder universe, not this provider list.\n\nexport const devOperationCapabilities = Object.freeze([\n${operationCapabilities
  .map((capability) => `  ${singleQuoted(capability)},`)
  .join('\n')}\n] as const)\n`

const operationMetadataIndexSource = `// Generated by scripts/generate-dev-runtime-contract.mjs from\n// docs/specs/dev-runtime-operations.json. Do not edit by hand.\n\n${operationEntries
  .map(([operation]) => {
    const fileName = `${operation.replace(/[^A-Za-z0-9_$]/g, '_')}`
    return `export * from './${fileName}'`
  })
  .join('\n')}\nexport * from './capabilities'\n`

const operationMetadataAggregate = operationEntries
  .map(([operation]) => {
    const exportName = operationMetadataExportName(operation)
    return `  ${JSON.stringify(operation)}: commandMetadata(operationMetadata.${exportName})`
  })
  .join(',\n')
const unformattedMetadataSource = `// Generated by scripts/generate-dev-runtime-contract.mjs from\n// docs/specs/dev-runtime-operations.json. Do not edit by hand.\n// Browser-safe operation metadata; request DSL and reply schema names stay in the server registry.\n\nimport * as operationMetadata from './dev-runtime-operation-metadata/index'\n\nexport * from './dev-runtime-operation-metadata/index'\n\n// Keep the dynamic compatibility map compact without widening its public shape.\nfunction commandMetadata<T extends { capabilities: unknown; resource: unknown }>(definition: T): Pick<T, 'capabilities' | 'resource'> {\n  return { capabilities: definition.capabilities, resource: definition.resource }\n}\n\nexport const devOperationMetadata = {\n${operationMetadataAggregate}\n} as const\n`

const formatted = spawnSync('bunx', ['oxfmt', '--stdin-filepath', outputPath], {
  cwd: root,
  encoding: 'utf8',
  input: unformattedSource,
})
if (formatted.status !== 0) {
  process.stderr.write(formatted.stderr)
  process.exit(formatted.status ?? 1)
}
const source = formatted.stdout

const expectedOperationMetadataFiles = new Map([
  ...operationMetadataFiles,
  ['capabilities.ts', operationMetadataCapabilitiesSource],
  ['index.ts', operationMetadataIndexSource],
])

async function currentOperationMetadataFiles() {
  const entries = await readdir(operationMetadataDirectory, { withFileTypes: true }).catch(() => [])
  return new Map(
    await Promise.all(
      entries.map(async (entry) => [
        entry.name,
        entry.isFile()
          ? await readFile(path.join(operationMetadataDirectory, entry.name), 'utf8')
          : null,
      ])
    )
  )
}

function reportStaleOutput(filePath) {
  console.error(`${path.relative(root, filePath)} is out of date`)
}

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '')
  if (current !== source) {
    reportStaleOutput(outputPath)
    process.exit(1)
  }
  const currentMetadata = await readFile(metadataOutputPath, 'utf8').catch(() => '')
  const formattedMetadata = spawnSync('bunx', ['oxfmt', '--stdin-filepath', metadataOutputPath], {
    cwd: root,
    encoding: 'utf8',
    input: unformattedMetadataSource,
  })
  if (formattedMetadata.status !== 0) {
    process.stderr.write(formattedMetadata.stderr)
    process.exit(formattedMetadata.status ?? 1)
  }
  if (currentMetadata !== formattedMetadata.stdout) {
    reportStaleOutput(metadataOutputPath)
    process.exit(1)
  }
  const currentFiles = await currentOperationMetadataFiles()
  for (const [fileName, expected] of expectedOperationMetadataFiles) {
    if (currentFiles.get(fileName) !== expected) {
      reportStaleOutput(path.join(operationMetadataDirectory, fileName))
      process.exit(1)
    }
  }
  for (const fileName of currentFiles.keys()) {
    if (!expectedOperationMetadataFiles.has(fileName)) {
      reportStaleOutput(path.join(operationMetadataDirectory, fileName))
      process.exit(1)
    }
  }
} else {
  const currentFiles = await currentOperationMetadataFiles()
  const unexpectedFiles = [...currentFiles.keys()].filter(
    (fileName) => !expectedOperationMetadataFiles.has(fileName)
  )
  for (const fileName of unexpectedFiles) {
    const content = currentFiles.get(fileName)
    if (
      typeof content !== 'string' ||
      !content.startsWith('// Generated by scripts/generate-dev-runtime-contract.mjs from\n')
    ) {
      console.error(
        `refusing to overwrite unexpected file ${path.relative(operationMetadataDirectory, path.join(operationMetadataDirectory, fileName))}`
      )
      process.exit(1)
    }
  }

  await writeFile(outputPath, source)
  const formattedMetadata = spawnSync('bunx', ['oxfmt', '--stdin-filepath', metadataOutputPath], {
    cwd: root,
    encoding: 'utf8',
    input: unformattedMetadataSource,
  })
  if (formattedMetadata.status !== 0) {
    process.stderr.write(formattedMetadata.stderr)
    process.exit(formattedMetadata.status ?? 1)
  }
  await writeFile(metadataOutputPath, formattedMetadata.stdout)
  await mkdir(operationMetadataDirectory, { recursive: true })
  await Promise.all(
    [...expectedOperationMetadataFiles].map(([fileName, content]) =>
      writeFile(path.join(operationMetadataDirectory, fileName), content)
    )
  )
  await Promise.all(
    unexpectedFiles.map((fileName) => rm(path.join(operationMetadataDirectory, fileName)))
  )
}
