// Synthetic fixtures for the cross-machine and cross-platform transfer qualification.
//
// Every machine here is a profile, not a machine: a namespace, the pinned client version, the platform it runs on and
// the toolchain identity the build computes for it. The toolchain identities have the shape the repository's own
// `scripts/orch-toolchain.mjs` computes (`<platform>-<arch>.<libc>.node<version>-<sha>.bun<version>-<sha>`), and
// they hold a version and a hash of each binary, the platform and the libc, but never a path.
//
// The entries are synthetic and carry no data of this machine: the archives are generated byte patterns and a
// multipart boundary, so a transfer that loses or reorders bytes shows up.

import { machine, toolchainId } from './vp-r2-cache-transfer.mjs'

/** The client version this repository pins. */
export const PINNED_CLIENT = '1.3.0'

/** A client version that is not the pinned one. */
export const OTHER_CLIENT = '1.4.0'

/** The namespace this repository's entries belong to. */
export const NAMESPACE = 'adea-ai/adea'

/** Another namespace, for the case where two repositories share one store. */
export const OTHER_NAMESPACE = 'adea-ai/another-repository'

const DARWIN_TOOLCHAIN = toolchainId({
  platform: 'darwin',
  arch: 'arm64',
  libc: 'na',
  node: '24.21.0',
  bun: '1.4.3',
  nodeSha: 'e4b5a3af0e05b0a4f2b7c1d3e5f6a7b8c9d0e1f2a3b4c5d6e7f8091a2b3c4d5e',
  bunSha: '28c7dd0a0691a2b3c4d5e6f708192a3b4c5d6e7f8091a2b3c4d5e6f708192a3b4',
})

const LINUX_TOOLCHAIN = toolchainId({
  platform: 'linux',
  arch: 'x64',
  libc: 'glibc2.39',
  node: '24.21.0',
  bun: '1.4.3',
  nodeSha: '11aa22bb33cc44dd55ee66ff77889900112233445566778899aabbccddeeff',
  bunSha: '99aabbccddeeff00112233445566778899aabbccddeeff0011223344556677',
})

/**
 * The machines of the qualification:
 *
 *   - `darwin-a` and `darwin-b`: two checkouts of the same repository on the same platform and the same runtimes.
 *     They have the same toolchain identity, because the identity holds no path, so they are one trust domain and may
 *     share entries. This is the compatible cross-machine transfer.
 *   - `linux`: the same repository on another platform. Its toolchain identity differs, so it is another domain and
 *     shares nothing. This is the cross-platform boundary.
 *   - `darwin-other-client`: the same platform with another client version.
 *   - `darwin-other-namespace`: another repository on the same platform, sharing one store.
 */
export function machines() {
  return {
    'darwin-a': machine({
      namespace: NAMESPACE,
      client: PINNED_CLIENT,
      toolchain: DARWIN_TOOLCHAIN,
      platform: 'darwin',
      arch: 'arm64',
    }),
    'darwin-b': machine({
      namespace: NAMESPACE,
      client: PINNED_CLIENT,
      toolchain: DARWIN_TOOLCHAIN,
      platform: 'darwin',
      arch: 'arm64',
    }),
    linux: machine({
      namespace: NAMESPACE,
      client: PINNED_CLIENT,
      toolchain: LINUX_TOOLCHAIN,
      platform: 'linux',
      arch: 'x64',
    }),
    'darwin-other-client': machine({
      namespace: NAMESPACE,
      client: OTHER_CLIENT,
      toolchain: DARWIN_TOOLCHAIN,
      platform: 'darwin',
      arch: 'arm64',
    }),
    'darwin-other-namespace': machine({
      namespace: OTHER_NAMESPACE,
      client: PINNED_CLIENT,
      toolchain: DARWIN_TOOLCHAIN,
      platform: 'darwin',
      arch: 'arm64',
    }),
  }
}

/** The toolchain identities the fixtures use, so a test can name them. */
export const TOOLCHAINS = { darwin: DARWIN_TOOLCHAIN, linux: LINUX_TOOLCHAIN }

/** A synthetic entry whose archive holds every byte value, so a transfer that loses bytes shows up. */
export function binaryEntry(seed = 'binary') {
  const archive = Buffer.from(
    Array.from({ length: 512 }, (_, index) => (index + seed.length) % 256)
  )
  return {
    key: Buffer.from(`synthetic-entry-key:${seed}`, 'utf8'),
    secondaryKey: Buffer.from(`synthetic-task-key:${seed}`, 'utf8'),
    value: Buffer.from(`synthetic-entry-value:${seed}`, 'utf8'),
    blob: archive,
  }
}

/** A synthetic entry whose archive holds a multipart boundary as plain bytes. */
export function boundaryEntry(boundary = 'adea-boundary') {
  return {
    key: Buffer.from('synthetic-entry-key:boundary', 'utf8'),
    secondaryKey: Buffer.from('synthetic-task-key:boundary', 'utf8'),
    value: Buffer.from('synthetic-entry-value:boundary', 'utf8'),
    blob: Buffer.concat([
      Buffer.from('prefix', 'utf8'),
      Buffer.from(`--${boundary}--suffix`, 'utf8'),
      Buffer.from([0x00, 0xff, 0x0d, 0x0a]),
    ]),
  }
}

/** A synthetic entry whose archive is larger than the other fixtures, to show the size bounds hold. */
export function largeEntry(bytes = 512 * 1024) {
  const archive = Buffer.alloc(bytes)
  for (let index = 0; index < bytes; index += 1) archive[index] = index % 251
  return {
    key: Buffer.from('synthetic-entry-key:large', 'utf8'),
    secondaryKey: Buffer.from('synthetic-task-key:large', 'utf8'),
    value: Buffer.from('synthetic-entry-value:large', 'utf8'),
    blob: archive,
  }
}
